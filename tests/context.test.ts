import test from "node:test";
import assert from "node:assert/strict";
import { compactSession } from "../src/core/context.js";
import type { PersistedSession } from "../src/core/session.js";
import type { ConversationMessage, MessageRole } from "../src/core/types.js";

test("compacts older messages and retains latest messages", () => {
  const session = fakeSession([
    text("user", "first request"),
    text("assistant", "first answer"),
    text("user", "second request"),
    text("assistant", "second answer"),
    text("user", "third request"),
    text("assistant", "third answer")
  ]);

  const report = compactSession(session, 2);
  assert.equal(report.compacted, true);
  assert.equal(report.beforeMessages, 6);
  assert.equal(report.afterMessages, 3);
  assert.equal(report.compactedMessages, 4);
  assert.equal(session.messages[0]?.role, "assistant");
  assert.equal(session.messages[1]?.blocks[0]?.type, "text");
  assert.equal(session.messages[1]?.blocks[0]?.type === "text" ? session.messages[1].blocks[0].text : "", "third request");
  const summary = session.messages[0]?.blocks[0];
  assert.equal(summary?.type, "text");
  assert.match(summary?.type === "text" ? summary.text : "", /Context summary generated by \/compact/);
});

test("skips compaction when there is not enough context", () => {
  const session = fakeSession([text("user", "short"), text("assistant", "ok")]);
  const report = compactSession(session, 6);
  assert.equal(report.compacted, false);
  assert.equal(session.messages.length, 2);
});

function fakeSession(messages: ConversationMessage[]): PersistedSession {
  return {
    version: 1,
    sessionId: "test-session",
    createdAt: "2026-06-16T00:00:00.000Z",
    updatedAt: "2026-06-16T00:00:00.000Z",
    workspaceRoot: process.cwd(),
    model: "qwen3:8b",
    messages,
    promptHistory: [],
    usage: { inputTokens: 0, outputTokens: 0 }
  };
}

function text(role: MessageRole, value: string): ConversationMessage {
  return {
    role,
    blocks: [{ type: "text", text: value }]
  };
}
