import test from "node:test";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { buildContextMonitorReport } from "../src/core/contextMonitor.js";
import { appendMessage, SessionStore } from "../src/core/session.js";
import type { RuntimeConfig } from "../src/core/types.js";

test("/context reports usage, tool ratio, compaction, and CCR entries", async () => {
  const workspace = await mkdtemp(path.join(os.tmpdir(), "code-agent-context-"));
  await mkdir(path.join(workspace, ".code-agent", "ccr"), { recursive: true });
  await writeFile(path.join(workspace, ".code-agent", "ccr", "entry.json"), "{}\n", "utf8");

  const store = new SessionStore(workspace);
  const session = await store.loadOrCreate(undefined, "qwen3:8b");
  appendMessage(session, { role: "user", blocks: [{ type: "text", text: "analyze project" }], usage: { inputTokens: 2, outputTokens: 0 } });
  appendMessage(session, {
    role: "tool",
    blocks: [{
      type: "tool_result",
      toolUseId: "tool-1",
      toolName: "read_file",
      output: { content: "line one\nline two\nline three" },
      isError: false
    }]
  });
  appendMessage(session, {
    role: "assistant",
    blocks: [{ type: "text", text: "Context summary generated by /compact\nsummary" }],
    usage: { inputTokens: 3, outputTokens: 4 }
  });

  const report = await buildContextMonitorReport(config(workspace), session);

  assert.equal(report.sessionId, session.sessionId);
  assert.equal(report.messages, 3);
  assert.equal(report.compactionDetected, true);
  assert.equal(report.ccrEntries, 1);
  assert.equal(report.cost.local, true);
  assert.equal(report.cost.estimatedUsd, 0);
  assert.equal(report.toolResultTokens > 0, true);
});

function config(workspaceRoot: string): RuntimeConfig {
  return {
    workspaceRoot,
    provider: "openai-compatible",
    model: "qwen3:8b",
    baseUrl: "http://localhost:11434/v1",
    apiKey: "ollama",
    permissionMode: "workspace-write",
    outputFormat: "json",
    maxTurns: 4,
    maxBudgetTokens: 2000,
    useLlm: false
  };
}
