import path from "node:path";
import type { PersistedSession } from "./session.js";

export interface SessionMetadata {
  id: string;
  title: string;
  summary?: string;
  workspaceRoot: string;
  createdAt: string;
  updatedAt: string;
  messageCount: number;
  model?: string;
  provider?: string;
  profile?: string;
  compacted?: boolean;
  lastUserMessagePreview?: string;
}

export type SessionSelectorResolution =
  | { kind: "none"; reason: "empty" | "not_found" }
  | { kind: "one"; session: PersistedSession }
  | { kind: "many"; sessions: PersistedSession[] };

export function toSessionMetadata(session: PersistedSession): SessionMetadata {
  return {
    id: session.sessionId,
    title: session.title ?? session.sessionId,
    ...(session.summary ? { summary: session.summary } : {}),
    workspaceRoot: session.workspaceRoot,
    createdAt: session.createdAt,
    updatedAt: session.updatedAt,
    messageCount: session.messages.length,
    ...(session.model ? { model: session.model } : {}),
    ...(session.provider ? { provider: session.provider } : {}),
    ...(session.profile ? { profile: session.profile } : {}),
    compacted: session.messages.some((message) =>
      message.blocks.some((block) => block.type === "text" && block.text.includes("Context summary generated by /compact"))
    ),
    ...(session.lastUserMessagePreview ? { lastUserMessagePreview: session.lastUserMessagePreview } : {})
  };
}

export function resolveSessionSelector(selector: string, sessions: PersistedSession[]): SessionSelectorResolution {
  const requested = stripOuterQuotes(selector.trim());
  if (!requested) {
    return { kind: "none", reason: "empty" };
  }

  if (["latest", "last", "recent"].includes(requested.toLowerCase())) {
    const latest = sessions[0];
    return latest ? { kind: "one", session: latest } : { kind: "none", reason: "not_found" };
  }

  if (/^\d+$/.test(requested)) {
    const index = Number(requested) - 1;
    const session = sessions[index];
    return session ? { kind: "one", session } : { kind: "none", reason: "not_found" };
  }

  const exact = sessions.find((session) => session.sessionId === requested);
  if (exact) {
    return { kind: "one", session: exact };
  }

  const prefixMatches = sessions.filter((session) => session.sessionId.startsWith(requested));
  if (prefixMatches.length === 1 && requested.length >= 4) {
    return { kind: "one", session: prefixMatches[0] as PersistedSession };
  }
  if (prefixMatches.length > 1) {
    return { kind: "many", sessions: prefixMatches };
  }

  const lowered = requested.toLowerCase();
  const fuzzyMatches = sessions.filter((session) => {
    const values = [
      session.title,
      session.summary,
      session.lastUserMessagePreview,
      path.basename(session.workspaceRoot)
    ].filter(Boolean).map((value) => String(value).toLowerCase());
    return values.some((value) => value.includes(lowered));
  });
  if (fuzzyMatches.length === 1) {
    return { kind: "one", session: fuzzyMatches[0] as PersistedSession };
  }
  if (fuzzyMatches.length > 1) {
    return { kind: "many", sessions: fuzzyMatches };
  }

  return { kind: "none", reason: "not_found" };
}

export function sameWorkspace(left: string, right: string): boolean {
  return path.resolve(left) === path.resolve(right);
}

function stripOuterQuotes(value: string): string {
  if ((value.startsWith("\"") && value.endsWith("\"")) || (value.startsWith("'") && value.endsWith("'"))) {
    return value.slice(1, -1).trim();
  }
  return value;
}
