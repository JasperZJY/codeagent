import { existsSync } from "node:fs";
import { readdir } from "node:fs/promises";
import path from "node:path";
import { estimateMessagesUsage } from "./context.js";
import type { ContextMonitorReport, ConversationMessage, RuntimeConfig } from "./types.js";
import type { PersistedSession } from "./session.js";

export async function buildContextMonitorReport(
  config: RuntimeConfig,
  session: PersistedSession
): Promise<ContextMonitorReport> {
  const activeUsage = estimateMessagesUsage(session.messages);
  const toolResultTokens = estimateToolResultTokens(session.messages);
  const estimatedActiveTokens = activeUsage.inputTokens + activeUsage.outputTokens;
  const ratio = estimatedActiveTokens > 0 ? toolResultTokens / estimatedActiveTokens : 0;
  const ccrEntries = await countCcrEntries(config.workspaceRoot);
  const cost = estimateCost(config, session.usage);
  return {
    sessionId: session.sessionId,
    messages: session.messages.length,
    promptHistory: session.promptHistory.length,
    usage: session.usage,
    estimatedActiveTokens,
    toolResultTokens,
    toolResultRatio: Number(ratio.toFixed(4)),
    compressionMode: config.contextCompression ?? "local",
    compactionDetected: session.messages.some((message) =>
      message.blocks.some((block) => block.type === "text" && block.text.includes("Context summary generated by /compact"))
    ),
    ccrEntries,
    cost
  };
}

function estimateToolResultTokens(messages: ConversationMessage[]): number {
  let tokens = 0;
  for (const message of messages) {
    for (const block of message.blocks) {
      if (block.type === "tool_result") {
        tokens += countTokens(safeStringify(block.output));
      }
    }
  }
  return tokens;
}

async function countCcrEntries(workspaceRoot: string): Promise<number> {
  const dir = path.join(workspaceRoot, ".code-agent", "ccr");
  if (!existsSync(dir)) {
    return 0;
  }
  return (await readdir(dir)).filter((entry) => entry.endsWith(".json")).length;
}

function estimateCost(config: RuntimeConfig, usage: { inputTokens: number; outputTokens: number }): ContextMonitorReport["cost"] {
  const local = isLocalModel(config);
  if (local) {
    return {
      provider: config.provider,
      model: config.model,
      local: true,
      estimatedUsd: 0,
      note: "Local model or Ollama-compatible endpoint; cost is treated as 0/unavailable."
    };
  }
  const pricing = staticPricing(config.model);
  if (!pricing) {
    return {
      provider: config.provider,
      model: config.model,
      local: false,
      note: "No static pricing entry is configured for this model; cost unavailable."
    };
  }
  const estimatedUsd = (usage.inputTokens / 1_000_000) * pricing.inputPerMillion +
    (usage.outputTokens / 1_000_000) * pricing.outputPerMillion;
  return {
    provider: config.provider,
    model: config.model,
    local: false,
    estimatedUsd: Number(estimatedUsd.toFixed(6)),
    note: "Static approximate estimate; check provider billing for authoritative pricing."
  };
}

function staticPricing(model: string): { inputPerMillion: number; outputPerMillion: number } | undefined {
  const normalized = model.toLowerCase();
  if (normalized.includes("gpt-4.1-mini")) {
    return { inputPerMillion: 0.4, outputPerMillion: 1.6 };
  }
  if (normalized.includes("gpt-4o-mini")) {
    return { inputPerMillion: 0.15, outputPerMillion: 0.6 };
  }
  return undefined;
}

function isLocalModel(config: RuntimeConfig): boolean {
  return /localhost|127\.0\.0\.1|host\.docker\.internal/i.test(config.baseUrl) ||
    /ollama/i.test(config.apiKey) ||
    /qwen|llama|mistral|gemma/i.test(config.model);
}

function countTokens(value: string): number {
  return value.split(/\s+/).filter(Boolean).length;
}

function safeStringify(value: unknown): string {
  if (typeof value === "string") {
    return value;
  }
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}
