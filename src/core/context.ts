import type { ContentBlock, ConversationMessage, TokenUsage } from "./types.js";
import type { PersistedSession } from "./session.js";

export interface ContextCompactionReport {
  sessionId: string;
  compacted: boolean;
  beforeMessages: number;
  afterMessages: number;
  compactedMessages: number;
  retainedMessages: number;
  keepMessages: number;
  summaryPreview: string;
  usage: TokenUsage;
}

export function compactSession(session: PersistedSession, keepMessages = 6): ContextCompactionReport {
  const normalizedKeep = normalizeKeepMessages(keepMessages);
  const beforeMessages = session.messages.length;

  if (beforeMessages <= normalizedKeep + 1) {
    return {
      sessionId: session.sessionId,
      compacted: false,
      beforeMessages,
      afterMessages: beforeMessages,
      compactedMessages: 0,
      retainedMessages: beforeMessages,
      keepMessages: normalizedKeep,
      summaryPreview: "Nothing to compact.",
      usage: session.usage
    };
  }

  const splitIndex = Math.max(0, beforeMessages - normalizedKeep);
  const olderMessages = session.messages.slice(0, splitIndex);
  const retainedMessages = session.messages.slice(splitIndex);
  const summaryText = buildContextSummary(olderMessages);
  const summaryMessage: ConversationMessage = {
    role: "assistant",
    blocks: [{ type: "text", text: summaryText }],
    usage: {
      inputTokens: 0,
      outputTokens: countTokens(summaryText)
    }
  };

  session.messages = [summaryMessage, ...retainedMessages];
  session.usage = estimateMessagesUsage(session.messages);

  return {
    sessionId: session.sessionId,
    compacted: true,
    beforeMessages,
    afterMessages: session.messages.length,
    compactedMessages: olderMessages.length,
    retainedMessages: retainedMessages.length,
    keepMessages: normalizedKeep,
    summaryPreview: shorten(summaryText, 400),
    usage: session.usage
  };
}

export function estimateMessagesUsage(messages: ConversationMessage[]): TokenUsage {
  return messages.reduce<TokenUsage>(
    (usage, message) => {
      const text = message.blocks.map(blockToText).join("\n");
      const tokens = countTokens(text);
      if (message.role === "assistant") {
        usage.outputTokens += tokens;
      } else {
        usage.inputTokens += tokens;
      }
      return usage;
    },
    { inputTokens: 0, outputTokens: 0 }
  );
}

function buildContextSummary(messages: ConversationMessage[]): string {
  const bullets = messages.flatMap(messageToBullets).slice(0, 24);
  const lines = [
    "Context summary generated by /compact.",
    `Compressed messages: ${messages.length}.`,
    "",
    "Important prior context:"
  ];
  if (bullets.length === 0) {
    lines.push("- No textual content was available in the compacted messages.");
  } else {
    lines.push(...bullets.map((bullet) => `- ${bullet}`));
  }
  return lines.join("\n");
}

function messageToBullets(message: ConversationMessage): string[] {
  return message.blocks
    .map((block) => blockToBullet(message.role, block))
    .filter((value): value is string => Boolean(value));
}

function blockToBullet(role: ConversationMessage["role"], block: ContentBlock): string | undefined {
  if (block.type === "text") {
    const text = normalizeInline(block.text);
    return text ? `${role}: ${shorten(text, 220)}` : undefined;
  }
  if (block.type === "tool_result") {
    const output = normalizeInline(safeStringify(block.output));
    const state = block.isError ? "error" : "ok";
    return `tool:${block.toolName} ${state}: ${shorten(output, 220)}`;
  }
  if (block.type === "tool_use") {
    return `tool_use:${block.name}: ${shorten(normalizeInline(safeStringify(block.input)), 220)}`;
  }
  return undefined;
}

function blockToText(block: ContentBlock): string {
  if (block.type === "text") {
    return block.text;
  }
  if (block.type === "tool_result") {
    return safeStringify(block.output);
  }
  return `${block.name} ${safeStringify(block.input)}`;
}

function normalizeKeepMessages(value: number): number {
  if (!Number.isFinite(value)) {
    return 6;
  }
  return Math.max(0, Math.floor(value));
}

function normalizeInline(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

function shorten(value: string, maxLength: number): string {
  if (value.length <= maxLength) {
    return value;
  }
  return `${value.slice(0, Math.max(0, maxLength - 3))}...`;
}

function safeStringify(value: unknown): string {
  if (typeof value === "string") {
    return value;
  }
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

function countTokens(value: string): number {
  return value.split(/\s+/).filter(Boolean).length;
}
